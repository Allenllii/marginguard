import assert from 'node:assert/strict';
import { copyFile, mkdir, readFile, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

// Static GitHub Pages build: pages/ + the forced-offline Worker bundled into a
// classic service worker. Expects offline-dist/server/index.js to be current
// (npm run build:pages builds it first).
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const out = resolve(root, 'pages-dist');
await readFile(resolve(root, 'offline-dist/server/index.js'));
await rm(out, { recursive: true, force: true });
await mkdir(out);
await build({ entryPoints: [resolve(root, 'pages/sw.js')], bundle: true, format: 'iife', platform: 'browser', target: 'es2022', outfile: resolve(out, 'sw.js'), legalComments: 'inline', logLevel: 'warning', banner: { js: '/* eslint-disable */ // Generated by scripts/build-pages.mjs' } });
for (const file of ['index.html', 'pages-shim.js']) await copyFile(resolve(root, 'pages', file), resolve(out, file));

// Smoke: run the built sw.js against a fake service-worker global under a sub-path scope.
const origin = 'https://pages.example', listeners = {};
const self = { registration: { scope: `${origin}/marginguard/` }, location: new URL(`${origin}/marginguard/sw.js`), clients: { claim: async () => {} }, skipWaiting() {}, addEventListener: (type, fn) => { listeners[type] = fn; } };
new Function('self', await readFile(resolve(out, 'sw.js'), 'utf8'))(self);
const send = (path, init = {}, mode = 'cors') => {
  const request = new Request(new URL(path, origin), init); Object.defineProperty(request, 'mode', { value: mode });
  let reply = null; listeners.fetch({ request, respondWith: value => { reply = value; } }); return reply;
};
const page = await send('/marginguard/', {}, 'navigate'); const html = await page.text();
assert.equal(page.status, 200); assert.match(html, /MarginGuard/u); assert.match(html, /<script src="pages-shim\.js"><\/script><\/head>/u);
for (const [, asset] of html.matchAll(/(?:src|href)="(\/assets\/[^"]+)"/gu)) assert.equal((await send(asset)).status, 200, asset);
assert.equal((await (await send('/api/health')).json()).provider.mode, 'fixture');
assert.match(await (await send('/api/template')).text(), /^order_id,/u);
const csv = await readFile(resolve(root, 'data/northstar-demo.csv'), 'utf8');
const analysis = await send('/api/analyze', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ csv }) });
assert.equal(analysis.status, 200); assert.equal((await analysis.json()).orders.length, 504);
assert.equal((await send('/api/analyze', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' }, 'navigate')).status, 403);
assert.equal(send('/marginguard/pages-shim.js'), null); assert.equal(send('https://other.example/x'), null);
console.log(`Built ${out}; service-worker smoke passed under /marginguard/ (page, assets, health, template, CSV analyze, cross-site POST refused).`);
